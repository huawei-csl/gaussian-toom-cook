# libgtc calls a few mpn functions that every libgmp exports but that only
# GMP's private gmp-impl.h declares.  This script takes their declarations
# verbatim from the GMP 6.3.0 source and writes them to OUT:
#
#   tools/fetch_gmp.sh [OUT]          (default build/gmp_decls.h)
#
# The tarball is downloaded next to OUT once and checked against its
# SHA-256; GMP_TARBALL=/path/to/gmp-6.3.0.tar.xz uses a local copy instead.

set -eu

OUT=${1:-build/gmp_decls.h}
VER=6.3.0
SHA256=a3c2b80201b89e68616f4ad30bc66aee4927c3ce50e33929ca819d5c43538898
URLS="https://gmplib.org/download/gmp/gmp-$VER.tar.xz
https://ftp.gnu.org/gnu/gmp/gmp-$VER.tar.xz"

# the functions, and the scratch sizes of GMP's Toom functions
FUNCS="mul_basecase toom22_mul toom33_mul toom44_mul toom6h_mul bdiv_dbm1c
rsh1add_n rsh1sub_n addlsh1_n sublsh1_n rsblsh1_n addlsh2_n rsblsh2_n"
ITCH="toom22_mul toom33_mul toom44_mul"

die () { echo "fetch_gmp.sh: $*" >&2; exit 1; }

dir=$(dirname "$OUT")
mkdir -p "$dir"
tarball=${GMP_TARBALL:-$dir/gmp-$VER.tar.xz}

if [ ! -f "$tarball" ]; then
  tmp=$tarball.part
  for url in $URLS; do
    rm -f "$tmp"
    echo "fetch_gmp.sh: downloading $url" >&2
    if command -v curl >/dev/null 2>&1; then
      curl -fsSL -o "$tmp" "$url" && break
    else
      wget -q -O "$tmp" "$url" && break
    fi
  done
  [ -s "$tmp" ] || die "could not download gmp-$VER.tar.xz"
  mv "$tmp" "$tarball"
fi

if command -v sha256sum >/dev/null 2>&1; then
  sum=$(sha256sum "$tarball" | cut -d' ' -f1)
else
  sum=$(shasum -a 256 "$tarball" | cut -d' ' -f1)
fi
[ "$sum" = "$SHA256" ] || die "$tarball: SHA-256 $sum, expected $SHA256"

impl=$(mktemp)
trap 'rm -f "$impl" "$OUT.part"' EXIT
tar -xJOf "$tarball" "gmp-$VER/gmp-impl.h" > "$impl" \
  || die "no gmp-impl.h in $tarball"

{
  echo "/* Generated by tools/fetch_gmp.sh from gmp-$VER/gmp-impl.h"
  echo "   (GNU MP, LGPLv3 or GPLv2).  Do not edit.  */"
  echo
  echo "#ifndef GTC_GMP_DECLS_H"
  echo "#define GTC_GMP_DECLS_H"
  echo
  echo "#include <gmp.h>"
  echo
  for f in $FUNCS; do
    awk -v f="$f" '
      $0 ~ "^#define[ \t]+mpn_" f "[ \t]+__MPN\\(" f "\\)" { print; d = 1; next }
      d && /^__GMP_DECLSPEC/ && index($0, "mpn_" f " (") { print; exit }
    ' "$impl"
  done
  echo
  for f in $ITCH; do
    awk -v f="$f" '
      $0 ~ "^#define mpn_" f "_itch\\(" { p = 1 }
      p { print; if ($0 !~ /\\$/) exit }
    ' "$impl"
  done
  echo
  echo "#if GMP_NUMB_BITS != 64"
  echo "#error \"libgtc needs 64-bit limbs\""
  echo "#endif"
  echo
  echo "#endif"
} > "$OUT.part"

n=$(grep -c '^__GMP_DECLSPEC' "$OUT.part" || true)
m=$(grep -c '^#define mpn_[a-z0-9_]*_itch' "$OUT.part" || true)
[ "$n" -eq 13 ] && [ "$m" -eq 3 ] \
  || die "found $n of 13 declarations and $m of 3 scratch sizes in gmp-impl.h"
mv "$OUT.part" "$OUT"
trap - EXIT
rm -f "$impl"
